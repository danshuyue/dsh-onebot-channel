/**
 * 中文名 → 编号。同一名字对应多个编号时只留第一个 ——
 * 「晕」有 17 和 34、「OK」有 124 等，取编号小的那个。
 */
const FACE_IDS = (() => {
  const map = new Map()
  for (const [id, name] of FACE_NAMES) {
    if (!map.has(name)) map.set(name, id)
  }
  return map
})()

/** 掐短文本，表情名别把整行撑爆。 */
function clip(text, max = 20) {
  const value = String(text ?? '').trim()
  return value.length > max ? `${value.slice(0, max)}…` : value
}

/** 经典表情（face）：有 cid 就查中文名，查不到就把编号原样报出来。 */
export function faceTextOf(data) {
  const cid = String(data?.cid ?? data?.id ?? '').trim()
  if (cid === '') return '[表情]'
  const name = FACE_NAMES.get(Number(cid))
  return name !== undefined ? `[表情:${name}]` : `[表情:${cid}]`
}

/**
 * 商城大表情（mface）：优先用 summary（官方给的表情标题），其次 key / emoji_id。
 * 都没有就退回「[表情]」，别让 default 分支把它渲染成 [mface] 这种没人看得懂的原始类型名。
 */
export function mfaceTextOf(data) {
  const summary = clip(data?.summary ?? '')
  if (summary !== '') return `[表情:${summary}]`
  const key = clip(data?.key ?? '')
  if (key !== '') return `[表情:${key}]`
  const emojiId = clip(data?.emoji_id ?? '')
  if (emojiId !== '') return `[表情:${emojiId}]`
  return '[表情]'
}

/** 任意表情段 → 文本；不是表情段返回空串。 */
export function emojiTextOf(segment) {
  switch (segment?.type) {
    case 'face':
      return faceTextOf(segment?.data)
    case 'mface':
      return mfaceTextOf(segment?.data)
    default:
      return ''
  }
}

/**
 * 出站：把「中文名或数字编号」解析成 face 段的 id。
 * 返回 null 表示不认识 —— 调用方要报错，不能发空表情。
 */
export function faceIdOf(nameOrId) {
  const raw = String(nameOrId ?? '').trim()
  if (raw === '') return null
  // 纯数字直接当编号用（哪怕不在名表里，协议端也认）
  if (/^\d+$/.test(raw)) {
    const id = Number(raw)
    return Number.isSafeInteger(id) && id >= 0 ? id : null
  }
  // 中文名精确匹配
  const exact = FACE_IDS.get(raw)
  if (exact !== undefined) return exact
  // 允许带修饰的写法：「呲牙笑」「可爱的呲牙」这种包含关系
  for (const [name, id] of FACE_IDS) {
    if (raw.includes(name)) return id
  }
  return null
}

/** 出站：face 段。id 认不出来就抛错。 */
export function faceSegmentOf(nameOrId) {
  const id = faceIdOf(nameOrId)
  if (id === null) {
    throw new Error(`不认识的 QQ 表情：${String(nameOrId)}（可以给中文名如「呲牙」，或直接给编号）`)
  }
  return { type: 'face', data: { id: String(id) } }
}

/** 出站表情的可选清单，给工具描述用 —— 让 agent 知道能发什么。 */
export function faceNameList() {
  return [...FACE_IDS.entries()].map(([name, id]) => `${name}(${id})`)
}
